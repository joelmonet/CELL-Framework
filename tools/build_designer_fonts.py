#!/usr/bin/env python3
"""Build the UI Designer's offline font data with fontTools and Brotli."""

import argparse
import base64
import io
import json
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont


ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "assets"
RAJDHANI_REVISION = "8772f86137e17678cbd3584ca9a3c9486c3e7e50"


def encode_face(path, family, style, unicode_ranges):
    font = TTFont(path, recalcTimestamp=False)
    options = subset.Options()
    options.name_IDs = ["*"]
    options.name_languages = ["*"]
    subsetter = subset.Subsetter(options=options)
    subsetter.populate(unicodes=[code for start, end in unicode_ranges for code in range(start, end + 1)])
    subsetter.subset(font)

    postscript = family.replace(" ", "")
    names = {
        1: family, 2: style, 3: f"{family} {style}",
        4: f"{family} {style}", 6: f"{postscript}-{style}",
        16: family, 17: style, 18: f"{family} {style}",
        21: family, 22: style, 25: postscript,
    }
    for record in font["name"].names:
        if record.nameID in names:
            record.string = names[record.nameID]
    font.flavor = "woff2"
    out = io.BytesIO()
    font.save(out)
    return base64.b64encode(out.getvalue()).decode("ascii")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("rajdhani_sources", type=Path, help=(
        "directory with Rajdhani-Light, -Regular, -Medium and -Bold TTF sources from "
        f"https://github.com/google/fonts/tree/{RAJDHANI_REVISION}/ofl/rajdhani"
    ))
    args = parser.parse_args()
    latin_and_symbols = [(0x20, 0x24F), (0x1E00, 0x1EFF), (0x2000, 0x22FF), (0x25A0, 0x25FF)]
    sans = encode_face(ASSETS / "Inter.ttf", "Cell Panel Sans", "Regular",
                       latin_and_symbols + [(0x370, 0x52F), (0x1F00, 0x1FFF)])
    condensed = []
    for weight, style in [(300, "Light"), (400, "Regular"), (500, "Medium"), (600, "SemiBold"), (700, "Bold")]:
        directory = ASSETS if weight == 600 else args.rajdhani_sources
        path = directory / f"Rajdhani-{style}.ttf"
        condensed.append({"weight": str(weight), "data": encode_face(
            path, "Cell Panel Condensed", style, latin_and_symbols + [(0x900, 0x97F), (0xA8E0, 0xA8FF)])})

    fonts = {
        "panel-sans": {"family": "Cell Panel Sans", "license": (ASSETS / "OFL.txt").read_text(),
                       "faces": [{"weight": "100 900", "data": sans}]},
        "panel-condensed": {"family": "Cell Panel Condensed", "license": (ASSETS / "Rajdhani-OFL.txt").read_text(),
                            "faces": condensed},
    }
    output = ROOT / "examples" / "ui_designer" / "fonts.js"
    output.write_text(
        "// Generated by tools/build_designer_fonts.py. See the included SIL OFL notices.\n"
        f"// Rajdhani source revision: {RAJDHANI_REVISION}\n"
        "const CellDesignerFonts = " + json.dumps(fonts, indent=4) + ";\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
